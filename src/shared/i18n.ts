const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { fr, en };

/**
 * Traduit une cle, avec interpolation des parametres.
 * Une cle absente de la langue courante retombe sur le francais.
 */
export function translate(
  language: Language,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[language]?.[key] ?? fr[key] ?? key;
  if (!params) return template;

  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

export type Translator = (key: TranslationKey, params?: Record<string, string | number>) => string;

/** Construit la fonction de traduction pour une langue. */
export function createTranslator(language: Language): Translator {
  return (key, params) => translate(language, key, params);
}
